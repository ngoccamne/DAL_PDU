"""Writes the build identity header from the git revision of the PDU repository.

The output is firmware/DAL_PDU/DAL_PDU/src/dev/M1_Sys/Version/build_id.h. The file is written only
when its content changes, so an unchanged tree does not trigger a rebuild. Run it before every
firmware build (Studio pre-build event, or the tests Makefile).

Without git the build is reported as "nogit", with code 0 and the dirty flag set.
"""
import os
import subprocess

TOOLS = os.path.dirname(os.path.abspath(__file__))
PDU = os.path.dirname(TOOLS)
OUT = os.path.join(PDU, "firmware", "DAL_PDU", "DAL_PDU", "src", "dev", "M1_Sys", "Version", "build_id.h")
DIRTY_BIT = 1 << 28
HASH_MASK = 0x0FFFFFFF


# git may not be on the PATH of a Studio or make session, so the usual install locations are tried too.
GIT_CANDIDATES = ["git", r"C:\Program Files\Git\cmd\git.exe", r"C:\Program Files\Git\mingw64\bin\git.exe"]


def git(*args):
    for candidate in GIT_CANDIDATES:
        try:
            result = subprocess.run([candidate, "-c", "safe.directory=" + PDU.replace("\\", "/"), *args],
                                    cwd=PDU, capture_output=True, text=True, check=True)
        except (OSError, subprocess.CalledProcessError):
            continue
        return result.stdout.strip()
    return None


def build_identity():
    short = git("rev-parse", "--short=7", "HEAD")
    if not short:
        return "nogit", DIRTY_BIT
    dirty = bool(git("status", "--porcelain"))
    code = int(short, 16) & HASH_MASK
    if dirty:
        code |= DIRTY_BIT
    name = short + ("-dirty" if dirty else "")
    return name, code


def render(name, code):
    return (
        "/* Generated by tools/gen_build_id.py. Do not edit. */\n"
        "#ifndef BUILD_ID_H_\n"
        "#define BUILD_ID_H_\n\n"
        '#define FIRMWARE_BUILD_ID "%s"\n'
        "/* Bit 28 is the dirty flag. Bits 0 to 27 are the short commit hash. */\n"
        "#define FIRMWARE_BUILD_CODE 0x%08XUL\n\n"
        "#endif /* BUILD_ID_H_ */\n" % (name, code)
    )


def main():
    name, code = build_identity()
    text = render(name, code)
    try:
        with open(OUT, "r", encoding="utf-8", newline="") as f:
            if f.read().replace("\r\n", "\n") == text:
                print("build_id.h unchanged: %s" % name)
                return 0
    except FileNotFoundError:
        pass
    # The firmware sources use CRLF line endings.
    with open(OUT, "w", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", "\r\n"))
    print("build_id.h written: %s" % name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
