"""Build the PDU Release image from the checked-in Microchip Studio project."""

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
PROJECT = ROOT / "firmware" / "DAL_PDU" / "DAL_PDU"
CPROJ = PROJECT / "DAL_PDU.cproj"
OUTPUT = ROOT / "release"
TOOLCHAIN_FALLBACK = Path(
    r"C:\Program Files (x86)\Atmel\Studio\7.0\toolchain\avr8\avr8-gnu-toolchain\bin"
)
DFP_FALLBACK = Path(r"C:\Program Files (x86)\Atmel\Studio\7.0\Packs\atmel\ATmega_DFP\1.7.374")


def tool(name):
    directory = os.environ.get("AVR_TOOLCHAIN")
    if directory:
        candidate = Path(directory) / name
    else:
        found = shutil.which(name)
        candidate = Path(found) if found else TOOLCHAIN_FALLBACK / name
    if not candidate.exists() and candidate.with_suffix(".exe").exists():
        candidate = candidate.with_suffix(".exe")
    if not candidate.exists():
        raise SystemExit(f"{name} not found; set AVR_TOOLCHAIN to the AVR toolchain bin directory")
    return str(candidate)


def sources():
    tree = ET.parse(CPROJ)
    namespace = {"m": "http://schemas.microsoft.com/developer/msbuild/2003"}
    paths = []
    for item in tree.findall(".//m:Compile", namespace):
        relative = item.attrib["Include"]
        if not relative.lower().endswith(".c"):
            continue
        path = PROJECT / Path(relative.replace("\\", "/"))
        if not path.is_file():
            raise SystemExit(f"Project source is missing: {path}")
        paths.append(path)
    if not paths:
        raise SystemExit("No C sources found in DAL_PDU.cproj")
    return paths


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clean", action="store_true", help="remove only the files generated by this build")
    args = parser.parse_args()
    elf = OUTPUT / "DAL_PDU.elf"
    raw = OUTPUT / "DAL_PDU.hex"
    signed = OUTPUT / "DAL_PDU_signed.hex"
    if args.clean:
        for path in (elf, raw, signed, OUTPUT / "DAL_PDU.map"):
            path.unlink(missing_ok=True)
        return

    dfp = Path(os.environ.get("AVR_DFP", DFP_FALLBACK))
    include = [
        PROJECT / "src/dev/M2_BSP/Modbus",
        PROJECT / "src/dev/M4_MiddleWare/ThirdParty/freemodbus/modbus/include",
        PROJECT / "src/dev/M4_MiddleWare/ThirdParty/freemodbus/modbus/rtu",
    ]
    flags = [
        "-mmcu=atmega128a", "-std=gnu99", "-Os", "-funsigned-char",
        "-funsigned-bitfields", "-fpack-struct", "-fshort-enums",
        "-ffunction-sections", "-fdata-sections", "-mrelax", "-Wall",
        "-DNDEBUG", "-DMB_ASCII_ENABLED=0", "-DMB_FUNC_OTHER_REP_SLAVEID_ENABLED=0",
    ]
    if dfp.is_dir():
        flags += ["-B", str(dfp / "gcc/dev/atmega128a"), "-I" + str(dfp / "include")]
    flags += ["-I" + str(path) for path in include]
    OUTPUT.mkdir(exist_ok=True)
    command = [tool("avr-gcc"), *flags, *(str(path) for path in sources()),
               "-Wl,--gc-sections", "-Wl,--defsym=__TEXT_REGION_LENGTH__=0x1DF00",
               "-Wl,-Map=" + str(OUTPUT / "DAL_PDU.map"), "-lm", "-o", str(elf)]
    subprocess.run(command, cwd=PROJECT, check=True)
    subprocess.run([tool("avr-objcopy"), "-O", "ihex", "-R", ".eeprom",
                    "-R", ".fuse", "-R", ".lock", "-R", ".signature",
                    "-R", ".user_signatures", str(elf), str(raw)], check=True)
    subprocess.run([tool("avr-size"), str(elf)], check=True)
    print(f"Original firmware: {raw}")


if __name__ == "__main__":
    main()
